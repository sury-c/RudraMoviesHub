-- RUDRA MOVIES catalog schema (matches the application fields)
create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  description text,
  poster_url text,
  category text,
  release_year integer,
  language text,
  content_url text
);

-- Safe additive migration for projects created with the older starter schema.
alter table public.movies add column if not exists description text;
alter table public.movies add column if not exists poster_url text;
alter table public.movies add column if not exists category text;
alter table public.movies add column if not exists release_year integer;
alter table public.movies add column if not exists language text;
alter table public.movies add column if not exists content_url text;
alter table public.movies add column if not exists created_at timestamptz not null default now();

alter table public.movies enable row level security;
drop policy if exists "Public can view movies" on public.movies;
create policy "Public can view movies" on public.movies for select to anon, authenticated using (true);

