create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  year integer not null default 2026,
  language text not null default 'Kannada',
  genre text not null default 'Drama',
  rating text not null default '',
  duration text not null default '',
  synopsis text not null default '',
  cast text not null default '',
  tag text not null default 'NEW',
  art text not null default 'art-forest',
  symbol text not null default 'R',
  "posterUrl" text not null default '',
  "destinationUrl" text not null default '',
  "shortLink" text not null default '',
  created_at timestamptz not null default now()
);
-- The service-role key is only used server-side. Never put it in client code.
-- Keep Row Level Security enabled; the server API uses the service role only after admin auth.
alter table public.movies enable row level security;
